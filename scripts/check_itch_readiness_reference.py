#!/usr/bin/env python3
"""Additional synthetic readiness cases against an independent flat-book model.

Only the independent Python oracle is imported; no production decoder/book logic.
Existing qualified oracle identities are not regenerated by this supplemental set.
"""
import copy
import hashlib
import json
import subprocess
import sys
import check_itch_l3_reference as reference


def main(driver):
    cases = []
    start = [reference.system('O'), reference.directory(), reference.directory(2)]
    for locate in (1, 2):
        for side in (b'B', b'S'):
            for quantity in (1, 2, 65535, 2**32-1):
                events = start + [reference.add(11, quantity, side=side, locate=locate),
                                  reference.add(12, quantity, side=side, locate=locate),
                                  reference.execute(11, 1, 71, locate=locate),
                                  reference.replace(12, 13, 2, 10100, locate=locate),
                                  reference.cancel(13, 1, locate=locate),
                                  reference.cancel(13, locate=locate)]
                events += [reference.print_trade(90, locate=locate), reference.cross(91, locate=locate),
                           reference.broken(90, locate=locate)]
                events += [reference.system(c) for c in 'SQMEC']
                cases.append(reference.session(events, flags=1))
    tails = [reference.execute(999), reference.cancel(999), reference.add(11),
             reference.add(21, 0), reference.cancel(11, 0), reference.cancel(11, 11),
             reference.execute(11, 11), reference.replace(11, 11), reference.add(21, side=b'?'),
             reference.add(21)[:-1], reference.system('C')]
    for tail in tails:
        cases.append(reference.session(start + [reference.add(11), tail]))
    for prefix in ([reference.add(11)], [reference.execute(11)], [reference.directory()],
                   [reference.system('S')]):
        cases.append(reference.session(prefix))
    cases.append(reference.session(start + [reference.add(11, time=9), reference.cancel(11, time=8)], flags=4))
    # All complete A-payload truncations, including header-only partial messages.
    payload = reference.add(21)
    for length in range(1, len(payload)):
        cases.append(reference.session(start + [payload[:length]]))
    encoded = [' '.join(map(str, [c['flags'], *c['tick'], *c['lot']])) + ' ' + c['digest'] + ' ' +
               ' '.join(p.hex() for p in c['payloads']) for c in cases]
    process = subprocess.run([driver], input='\n'.join(encoded)+'\n', text=True,
                             capture_output=True, check=True, timeout=120)
    actual = [json.loads(line) for line in process.stdout.splitlines()]
    assert len(actual) == len(cases)
    digest = hashlib.sha256()
    candidates = 0
    for index, (case, observed) in enumerate(zip(cases, actual)):
        assert len(observed) == len(case['expected'])
        for ordinal, (expected, got) in enumerate(zip(case['expected'], observed)):
            mismatch = reference.first_difference(expected, got)
            assert mismatch is None, (index, ordinal, case['digest'], mismatch)
            digest.update(json.dumps(expected, sort_keys=True, separators=(',', ':')).encode()+b'\n')
            candidates += 1
    truth = cases[0]['expected'][4]
    for key in ('remaining', 'revision', 'journal'):
        wrong = copy.deepcopy(truth)
        wrong['books'][0][key] += 1
        assert reference.first_difference(truth, wrong) is not None
    print(json.dumps(dict(scope='synthetic readiness supplement, not observed validation',
                         sessions=len(cases), candidates=candidates, negative_controls=3,
                         canonical_sha256=digest.hexdigest()), sort_keys=True))


if __name__ == '__main__': main(sys.argv[1])
